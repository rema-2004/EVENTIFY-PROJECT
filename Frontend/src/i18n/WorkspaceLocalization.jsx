const ARABIC_LABEL_KEYS = Object.fromEntries(
    Object.entries(LABEL_KEYS).map(([, key]) => [ar.workspace[key], key]),
)
function normalizeLabel(value) {
    return value
        .normalize('NFKC')
        .replace(/[\u00a0\s]+/g, ' ')
        .replace(/[’‘]/g, "'")
        .replace(/[‐‑‒–—]/g, '-')
        .trim()
        .toLocaleLowerCase()
}

const NORMALIZED_LABEL_KEYS = Object.fromEntries(
    Object.entries({ ...LABEL_KEYS, ...ARABIC_LABEL_KEYS }).map(([label, key]) => [normalizeLabel(label), key]),
)
const ATTRIBUTE_NAMES = ['aria-label', 'placeholder', 'title', 'alt']
const ATTRIBUTE_SELECTOR = ATTRIBUTE_NAMES.map((attribute) => `[${attribute}]`).join(',')

function findLabelKey(value) {
    return LABEL_KEYS[value] || ARABIC_LABEL_KEYS[value] || NORMALIZED_LABEL_KEYS[normalizeLabel(value)]
}

// ---- Dynamic strings (dates, counts, relative times, "A · B" lists) -----------------------------
// Only applied while the UI is Arabic; whole-sentence translations always come from the dictionary.
const isArabicUi = () => i18nInstance.language?.toLowerCase().startsWith('ar') ?? false

const AR_MONTHS = {
    Jan: 'يناير', Feb: 'فبراير', Mar: 'مارس', Apr: 'أبريل', May: 'مايو', Jun: 'يونيو',
    Jul: 'يوليو', Aug: 'أغسطس', Sep: 'سبتمبر', Sept: 'سبتمبر', Oct: 'أكتوبر', Nov: 'نوفمبر', Dec: 'ديسمبر',
}
const MONTH_PATTERN = 'Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sept|Sep|Oct|Nov|Dec'

const TIME_UNITS = {
    minute: ['دقيقة', 'دقيقتين', 'دقائق', 'دقيقة'],
    hour: ['ساعة', 'ساعتين', 'ساعات', 'ساعة'],
    day: ['يوم', 'يومين', 'أيام', 'يومًا'],
    week: ['أسبوع', 'أسبوعين', 'أسابيع', 'أسبوعًا'],
    month: ['شهر', 'شهرين', 'أشهر', 'شهرًا'],
    year: ['سنة', 'سنتين', 'سنوات', 'سنة'],
}

function arabicCount(amount, unit) {
    const n = Number(amount)
    const forms = TIME_UNITS[unit]
    if (n === 1) return forms[0]
    if (n === 2) return forms[1]
    if (n >= 3 && n <= 10) return `${n} ${forms[2]}`
    return `${n} ${forms[3]}`
}

function localizeDates(value) {
    return value
        // 06 Sep 2026 — 3:27 AM
        .replace(new RegExp(`(\\d{1,2}) (${MONTH_PATTERN}) (\\d{4}) — (\\d{1,2}:\\d{2}) (AM|PM)`, 'g'),
            (_, d, m, y, time, ap) => `${d} ${AR_MONTHS[m]} ${y} — ${time} ${ap === 'AM' ? 'ص' : 'م'}`)
        // 02 Sept 20:14
        .replace(new RegExp(`(\\d{1,2}) (${MONTH_PATTERN}) (\\d{1,2}:\\d{2})`, 'g'), (_, d, m, time) => `${d} ${AR_MONTHS[m]} ${time}`)
        // Nov 12 - Dec 24, 2026
        .replace(new RegExp(`(${MONTH_PATTERN}) (\\d{1,2}) - (${MONTH_PATTERN}) (\\d{1,2}), (\\d{4})`, 'g'),
            (_, m1, d1, m2, d2, y) => `${d1} ${AR_MONTHS[m1]} - ${d2} ${AR_MONTHS[m2]} ${y}`)
        // Sep 3
        .replace(new RegExp(`^(${MONTH_PATTERN}) (\\d{1,2})$`), (_, m, d) => `${d} ${AR_MONTHS[m]}`)
        // Nov 10, 2026
        .replace(new RegExp(`(${MONTH_PATTERN}) (\\d{1,2}), (\\d{4})`, 'g'), (_, m, d, y) => `${d} ${AR_MONTHS[m]} ${y}`)
        // 3 days ago
        .replace(/(\d+) (minute|hour|day|week|month|year)s? ago/g, (_, n, unit) => `قبل ${arabicCount(n, unit)}`)
        .replace(/\byesterday\b/g, 'أمس')
}

