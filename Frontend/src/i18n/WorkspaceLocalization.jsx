const ARABIC_LABEL_KEYS = Object.fromEntries(
    Object.entries(LABEL_KEYS).map(([, key]) => [ar.workspace[key], key]),
)
function normalizeLabel(value) {
    return value
        .normalize('NFKC')
        .replace(/[\u00a0\s]+/g, ' ')
        .replace(/[’‘]/g, "'")
        .replace(/[‐‑‒–—]/g, '-')
        .trim()
        .toLocaleLowerCase()
}

const NORMALIZED_LABEL_KEYS = Object.fromEntries(
    Object.entries({ ...LABEL_KEYS, ...ARABIC_LABEL_KEYS }).map(([label, key]) => [normalizeLabel(label), key]),
)
const PARTIAL_LABELS = Object.entries({ ...LABEL_KEYS, ...ARABIC_LABEL_KEYS })
    .filter(([label]) => label.length >= 4 && /[\p{L}\p{N}]/u.test(label))
    .sort(([left], [right]) => right.length - left.length)

const ATTRIBUTE_NAMES = ['aria-label', 'placeholder', 'title', 'alt']
const ATTRIBUTE_SELECTOR = ATTRIBUTE_NAMES.map((attribute) => `[${attribute}]`).join(',')

function findLabelKey(value) {
    return LABEL_KEYS[value] || ARABIC_LABEL_KEYS[value] || NORMALIZED_LABEL_KEYS[normalizeLabel(value)]
}

function isWordCharacter(value) {
    return Boolean(value && /[\p{L}\p{N}]/u.test(value))
}

function translateValue(value, t) {
    const exactKey = findLabelKey(value)
    if (exactKey) return t(`workspace.${exactKey}`)

    let translated = value
    for (const [label, key] of PARTIAL_LABELS) {
        const search = label.toLocaleLowerCase()
        let start = 0
        while (start < translated.length) {
            const index = translated.toLocaleLowerCase().indexOf(search, start)
            if (index === -1) break

            const before = translated[index - 1]
            const after = translated[index + label.length]
            const leftMatches = !isWordCharacter(label[0]) || !isWordCharacter(before)
            const rightMatches = !isWordCharacter(label[label.length - 1]) || !isWordCharacter(after)
            if (leftMatches && rightMatches) {
                const replacement = t(`workspace.${key}`)
                translated = `${translated.slice(0, index)}${replacement}${translated.slice(index + label.length)}`
                start = index + replacement.length
            } else {
                start = index + label.length
            }
        }
    }
    return translated
}

function localizeElement(element, t) {
    if (element.matches('.material-symbols-outlined, [aria-hidden="true"]')) return

    for (const attribute of ATTRIBUTE_NAMES) {
        const value = element.getAttribute(attribute)
        if (!value) continue
        const translated = translateValue(value, t)
        if (translated !== value) element.setAttribute(attribute, translated)
    }
}

function localizeTextNode(textNode, t) {
    if (textNode.parentElement?.closest('script, style, textarea, .material-symbols-outlined, [aria-hidden="true"]')) return

    const originalText = textNode.nodeValue
    const trimmedText = originalText.trim()
    if (!trimmedText) return

    const translatedText = translateValue(trimmedText, t)
    if (translatedText !== trimmedText) {
        textNode.nodeValue = originalText.replace(trimmedText, translatedText)
    }
}

function localizeSubtree(root, t) {
    if (root.nodeType === Node.ELEMENT_NODE) localizeElement(root, t)
    if (root.nodeType === Node.TEXT_NODE) {
        localizeTextNode(root, t)
        return
    }

    root.querySelectorAll?.(ATTRIBUTE_SELECTOR).forEach((element) => localizeElement(element, t))

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
    let textNode
    while ((textNode = walker.nextNode())) {
        localizeTextNode(textNode, t)
    }
}

export default function WorkspaceLocalization() {
    const { pathname } = useLocation()
    const { t, i18n } = useTranslation()
    const isWorkspacePage = /^\/(app|admin|org)(\/|$)/.test(pathname)

    useEffect(() => {
        const root = document.getElementById('root')
        if (!isWorkspacePage || !root) return undefined

        localizeSubtree(root, t)
        const observer = new MutationObserver((records) => {
            records.forEach((record) => {
                if (record.type === 'characterData') {
                    localizeSubtree(record.target.parentElement, t)
                } else {
                    record.addedNodes.forEach((node) => localizeSubtree(node, t))
                    if (record.type === 'attributes') localizeElement(record.target, t)
                }
            })
        })

        observer.observe(root, {
            subtree: true,
            childList: true,
            characterData: true,
            attributes: true,
            attributeFilter: ATTRIBUTE_NAMES,
        })

        return () => observer.disconnect()
    }, [i18n.language, isWorkspacePage, t])

    return null
}