function translateValue(value, t, depth = 0) {
    const exactKey = findLabelKey(value)
    // English text is already English: never rewrite it, or a round trip through Arabic would not restore it.
    if (!isArabicUi() || depth > 3) return value
    if (exactKey) return t(`workspace.${exactKey}`)

    const dated = localizeDates(value)
    if (dated !== value) {
        const again = findLabelKey(dated)
        if (again) return t(`workspace.${again}`)
    }

    const recurse = (part) => translateValue(part, t, depth + 1)
    for (const [pattern, build] of DYNAMIC_RULES) {
        const match = dated.match(pattern)
        if (match) return build(match, recurse)
    }

    // "A · B · C" / "A • B": translate each segment on its own.
    if (/[·•]/.test(dated)) {
        const parts = dated.split(/([·•])/)
        const joined = parts.map((part, index) => {
            if (index % 2 || !part.trim()) return part
            const lead = part.match(/^\s*/)[0]
            const trail = part.match(/\s*$/)[0]
            return lead + recurse(part.trim()) + trail
        }).join('')
        if (joined !== dated) return joined
    }

    return dated
}

// Remember what we replaced so switching back to English restores it exactly.
const TEXT_ORIGINALS = new WeakMap()
const ATTR_ORIGINALS = new WeakMap()

function localizeElement(element, t) {
    if (element.matches('.material-symbols-outlined, [aria-hidden="true"]')) return

    for (const attribute of ATTRIBUTE_NAMES) {
        const value = element.getAttribute(attribute)
        if (!value) continue
        const saved = ATTR_ORIGINALS.get(element)?.[attribute]
        if (!isArabicUi()) {
            if (saved && saved.translated === value) {
                element.setAttribute(attribute, saved.original)
                delete ATTR_ORIGINALS.get(element)[attribute]
                continue
            }
        }
        const translated = translateValue(value, t)
        if (translated !== value) {
            if (isArabicUi()) {
                const store = ATTR_ORIGINALS.get(element) || {}
                store[attribute] = { original: value, translated }
                ATTR_ORIGINALS.set(element, store)
            }
            element.setAttribute(attribute, translated)
        }
    }
}

function localizeTextNode(textNode, t) {
    if (textNode.parentElement?.closest('script, style, textarea, .material-symbols-outlined, [aria-hidden="true"]')) return

    const originalText = textNode.nodeValue
    const saved = TEXT_ORIGINALS.get(textNode)
    if (!isArabicUi() && saved && saved.translated === originalText) {
        textNode.nodeValue = saved.original
        TEXT_ORIGINALS.delete(textNode)
        return
    }

    const trimmedText = originalText.trim()
    if (!trimmedText) return

    const translatedText = translateValue(trimmedText, t)
    if (translatedText !== trimmedText) {
        const next = originalText.replace(trimmedText, translatedText)
        if (isArabicUi()) TEXT_ORIGINALS.set(textNode, { original: originalText, translated: next })
        textNode.nodeValue = next
    }
}

function localizeSubtree(root, t) {
    if (root.nodeType === Node.ELEMENT_NODE) localizeElement(root, t)
    if (root.nodeType === Node.TEXT_NODE) {
        localizeTextNode(root, t)
        return
    }

    root.querySelectorAll?.(ATTRIBUTE_SELECTOR).forEach((element) => localizeElement(element, t))

    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT)
    let textNode
    while ((textNode = walker.nextNode())) {
        localizeTextNode(textNode, t)
    }
}

export default function WorkspaceLocalization() {
    const { pathname } = useLocation()
    const { t, i18n } = useTranslation()
    // Every route (visitor and auth pages included) goes through the same dictionary.
    const isWorkspacePage = Boolean(pathname)

    useEffect(() => {
        const root = document.getElementById('root')
        if (!isWorkspacePage || !root) return undefined

        localizeSubtree(root, t)
        const observer = new MutationObserver((records) => {
            records.forEach((record) => {
                if (record.type === 'characterData') {
                    localizeSubtree(record.target.parentElement, t)
                } else {
                    record.addedNodes.forEach((node) => localizeSubtree(node, t))
                    if (record.type === 'attributes') localizeElement(record.target, t)
                }
            })
        })

        observer.observe(root, {
            subtree: true,
            childList: true,
            characterData: true,
            attributes: true,
            attributeFilter: ATTRIBUTE_NAMES,
        })

        return () => observer.disconnect()
    }, [i18n.language, isWorkspacePage, t])

    return null
}
