import { test, before, after } from 'node:test'
import assert from 'node:assert/strict'
import { BASE, startApp, stopApp, newPage, bodyText } from './helpers.mjs'

let browser
before(async () => { browser = await startApp() })
after(async () => { await stopApp(browser) })

const submit = (page, scope = 'form') => page.click(`${scope} button[type=submit]`)

test('signup: validates, then navigates to /app', async () => {
    const page = await newPage(browser)
    await page.goto(BASE + '/auth/signup', { waitUntil: 'networkidle' })
    await submit(page)
    assert.match(await bodyText(page), /required|مطلوب/i)
    const inputs = page.locator('form input:not([type=checkbox]):not([type=hidden])')
    const names = await inputs.evaluateAll((els) => els.map((e) => e.name || e.id || e.type))
    const fill = async (re, v) => { const i = names.findIndex((n) => re.test(n)); if (i >= 0) await inputs.nth(i).fill(v) }
    await fill(/name/i, 'Osama Hattab'); await fill(/phone/i, '0791234567'); await fill(/email/i, 'osama@example.com')
    await fill(/^password$/i, 'Passw0rd!x'); await fill(/confirm/i, 'Different1!')
    await submit(page)
    assert.ok(page.url().endsWith('/auth/signup'), 'mismatched passwords must block')
    await fill(/confirm/i, 'Passw0rd!x')
    await submit(page)
    assert.ok(page.url().endsWith('/auth/signup'), 'terms must be accepted')
    await page.locator('form input[type=checkbox]').first().check({ force: true })
    await submit(page)
    await page.waitForURL(/\/app/)
    assert.deepEqual(page.errors, [])
})

test('login: disabled when empty, bad credentials rejected, org role navigates', async () => {
    const page = await newPage(browser)
    await page.goto(BASE + '/auth/login', { waitUntil: 'networkidle' })
    assert.ok(await page.locator('form button[type=submit]').isDisabled())
    await page.fill('#identifier', 'error@example.com')
    await page.fill('input[type=password]', 'abcdefgh')
    await submit(page)
    await page.waitForTimeout(300)
    assert.ok(page.url().endsWith('/auth/login'))
    await page.goto(BASE + '/auth/login', { waitUntil: 'networkidle' })
    await page.locator('[role=radio]').nth(1).click()
    await page.fill('#identifier', 'org@example.com')
    await page.fill('input[type=password]', 'Passw0rd!x')
    await submit(page)
    await page.waitForURL(/\/org\/dashboard/)
    assert.deepEqual(page.errors, [])
})

test('forgot password: rejects bad email, confirms good one', async () => {
    const page = await newPage(browser)
    await page.goto(BASE + '/auth/forgot-password', { waitUntil: 'networkidle' })
    await page.fill('form input', 'not-an-email@')
    await submit(page)
    await page.waitForTimeout(300)
    const bad = await bodyText(page)
    await page.fill('form input', 'osama@example.com')
    await submit(page)
    await page.waitForTimeout(1800)
    assert.notEqual(await bodyText(page), bad)
    assert.deepEqual(page.errors, [])
})

test('contact: validates, sends, clears the form', async () => {
    const page = await newPage(browser)
    await page.goto(BASE + '/contact', { waitUntil: 'networkidle' })
    await submit(page, '.contact-form')
    assert.ok(await page.locator('.contact-form [class*=error], .contact-form [aria-invalid=true]').count() > 0)
    const fields = page.locator('.contact-form input:not([type=hidden]), .contact-form textarea')
    const kinds = await fields.evaluateAll((els) => els.map((e) => e.type))
    for (let i = 0; i < kinds.length; i++) await fields.nth(i).fill(kinds[i] === 'email' ? 'osama@example.com' : 'Hello there')
    await submit(page, '.contact-form')
    await page.waitForTimeout(1600)
    assert.ok((await fields.evaluateAll((els) => els.map((e) => e.value))).every((v) => v === ''))
})

