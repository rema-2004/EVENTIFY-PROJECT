test('participant profile: add project / experience, translucent backdrop, scrolling', async () => {
    const page = await newPage(browser)
    await page.setViewportSize({ width: 1280, height: 600 })
    await page.goto(BASE + '/app/profile', { waitUntil: 'networkidle' })
    await page.evaluate(() => localStorage.removeItem('eventify:participant-profile'))
    await page.reload({ waitUntil: 'networkidle' })
    await page.getByRole('button', { name: 'Add project' }).first().click()
    const dialog = page.getByRole('dialog')
    const backdrop = dialog.locator('xpath=..')
    const style = await backdrop.evaluate((el) => ({ bg: getComputedStyle(el).backgroundColor, blur: getComputedStyle(el).backdropFilter }))
    assert.match(style.bg, /(rgba\(0, 0, 0, |oklab\(0 0 0 \/ )0?\.\d+/, 'backdrop must be translucent')
    assert.match(style.blur, /blur/)
    assert.equal(await page.evaluate(() => document.body.style.overflow), 'hidden', 'page behind must not scroll')
    assert.ok(await dialog.locator('[data-edit-body]').evaluate((el) => el.scrollHeight > el.clientHeight), 'dialog body must scroll on a short screen')
    const cancel = dialog.getByRole('button', { name: 'Cancel' })
    const box = await cancel.boundingBox()
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await page.mouse.down()
    await page.waitForTimeout(300)
    assert.notEqual(await cancel.evaluate((el) => getComputedStyle(el).transform), 'none', 'pressed button must visibly change')
    await page.mouse.move(5, 5)
    await page.mouse.up()
    await dialog.getByLabel('Project 3 Title').fill('My Graduation Project')
    await dialog.getByLabel('Project 3 Description').fill('Built with React')
    await dialog.getByRole('button', { name: /Add experience/ }).click()
    await dialog.getByLabel('Experience 3 Title').fill('Frontend Intern')
    await dialog.getByRole('button', { name: 'Remove this project' }).first().click()
    await dialog.getByRole('button', { name: 'Save' }).click()
    assert.equal(await page.evaluate(() => document.body.style.overflow), '', 'scroll restored after closing')
    await page.reload({ waitUntil: 'networkidle' })
    const text = await bodyText(page)
    assert.match(text, /My Graduation Project/)
    assert.match(text, /Frontend Intern/)
    assert.doesNotMatch(text, /NeuralMesh/)
    assert.deepEqual(page.errors, [])
})
